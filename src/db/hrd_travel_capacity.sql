-- เดินทางไปราชการ: ขออนุมัติในฐานะ — คนที่เป็นหัวหน้าหลายหน่วยเลือกได้ว่ายื่นในฐานะใด (สายอนุมัติต่างกัน)
--   เช่น หัวหน้ากลุ่มงานอายุรกรรม (ภารกิจตติยภูมิ) ที่เป็นหัวหน้ากลุ่มภารกิจด้านสุขภาพดิจิทัลด้วย
--   ในฐานะหัวหน้าภารกิจ = เสนอ ผอ. โดยตรง · ในฐานะหัวหน้ากลุ่มงาน = ผ่านหัวหน้าภารกิจต้นสังกัดก่อน
-- approval_capacity = mission:<id> / major:<id> / member:<id> (null = ไม่ต้องเลือก ใช้สายตามสังกัด)
-- capacity_label = ข้อความ ณ วันยื่น เช่น "หัวหน้ากลุ่มภารกิจด้านสุขภาพดิจิทัล" (ชื่อหน่วยเปลี่ยนภายหลังไม่กระทบ)
-- รันซ้ำได้
-- ══════════════════════════════════════════════════════════════════════════════
ALTER TABLE hrd_travel_requests
    ADD COLUMN IF NOT EXISTS approval_capacity VARCHAR(30),
    ADD COLUMN IF NOT EXISTS capacity_label VARCHAR(300);
COMMENT ON COLUMN hrd_travel_requests.approval_capacity IS 'ขออนุมัติในฐานะ: mission:<id> | major:<id> | member:<id> — null = สายตามสังกัด';
COMMENT ON COLUMN hrd_travel_requests.capacity_label IS 'ฐานะที่ยื่น ณ วันยื่น เช่น หัวหน้ากลุ่มภารกิจด้านสุขภาพดิจิทัล';
